"""Emit static C descriptors from the frozen, checksummed integer model."""
from pathlib import Path
import json,hashlib,math,sys
sys.path.insert(0,str(Path(__file__).resolve().parent))
from model_size import SIZE
R=Path(__file__).resolve().parents[1];m=json.loads((R/'model/quantized/model.json').read_text());blob=(R/'model/quantized/weights.bin').read_bytes()
assert hashlib.sha256(blob).hexdigest()==m['weights_sha256']
byid={n['id']:n for n in m['nodes']};byid[0]=dict(shape=[3,SIZE,SIZE],address=0x02000000,bytes=3*SIZE*SIZE)
out=['/* Generated by tools/export_network.py; do not hand-edit. */',
     '#define MODEL_NODE_COUNT 85u','#define MODEL_WEIGHT_BASE 0x04000000u',
     'static const YoloNode model_nodes[MODEL_NODE_COUNT] = {']
ops={'conv':1,'add':2,'concat':3,'maxpool':4,'upsample':5}
for n in m['nodes']:
    src=[byid[i] for i in n['inputs']];assert len(src)<=4
    addr=[s['address'] for s in src]+[0]*(4-len(src));sizes=[s['bytes'] for s in src]+[0]*(4-len(src))
    tables=[0x04000000+v for v in n.get('table_offsets',[])]+[0]*(4-len(n.get('table_offsets',[])))
    c,h,w=n['shape'];ic,ih,iw=src[0]['shape']
    fields=[n['id'],ops[n['op']],len(src),c,h,w,ic,ih,iw,n.get('kernel',0),n.get('stride',0),n.get('padding',0),n['bits'],int(n.get('activation')=='silu')]
    out.append(' {'+','.join(map(str,fields))+f",0x{n['address']:08x},"+
        '{'+','.join(hex(v) for v in addr)+'},{'+','.join(map(str,sizes))+'},{'+','.join(hex(v) for v in tables)+'},'+
        ','.join(hex(0x04000000+n[k]) if k in n else '0' for k in ('weight_offset','bias_offset','multiplier_offset','shift_offset','lut_offset'))+f",{n.get('weight_row_stride',0)}"+'},')
out+=['};','static const YoloHead model_heads[3] = {']
for i,ident in enumerate(m['heads']):
    n=byid[ident];_,h,w=n['shape'];anchors=[int(round(v)) for pair in m['detect']['anchors'][i] for v in pair]
    out.append(f" {{0x{n['address']:08x},{w},{h},{int(m['detect']['strides'][i])},{{"+','.join(map(str,anchors))+'}},')
out+=['};','static const char *const model_names[80] = {']
names=m['names'];names=[names[str(i)] for i in range(80)] if isinstance(names,dict) else names
out += [' '+json.dumps(n)+',' for n in names]+['};']
# Sigmoid sampled every 1/256 logit, signed Q10 inputs round to nearest LUT
# index; clamp |x|>=8. Q15 outputs. Bound <=1/2048 + 1/32768 in probability.
sig=[round(32768/(1+math.exp(-i/256))) for i in range(-2048,2049)]
out+=['static const uint16_t sigmoid_q15[4097] = {']
out += [','.join(map(str,sig[i:i+24]))+',' for i in range(0,len(sig),24)]+['};']
(R/'firmware/model_tables.h').write_text('\n'.join(out)+'\n')
print('Exported',len(m['nodes']),'C graph descriptors; frozen weights SHA256',m['weights_sha256'])
